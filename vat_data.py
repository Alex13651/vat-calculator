def find(query: str):
    q = norm(query)
    if not q:
        return [], False
    if q in INDEX:
        return [INDEX[q]], True

    hits = []
    for name, ru in INDEX.items():
        if name.startswith(q) or any(w.startswith(q) for w in name.split()):
            if ru not in hits:
                hits.append(ru)
    if not hits and len(q) >= 3:
        for name, ru in INDEX.items():
            if q in name and ru not in hits:
                hits.append(ru)
    if hits:
        return hits, len(hits) == 1

    close = difflib.get_close_matches(q, list(INDEX.keys()), n=5, cutoff=0.7)
    res = []
    for name in close:
        if INDEX[name] not in res:
            res.append(INDEX[name])
    return res, False

def fmt_rate(r: float) -> str:
    return f"{r:g}%"

def fmt_rate_full(c: dict) -> str:
    if c["rate"] is None:
        return "нет"
    base = fmt_rate(c["rate"])
    if c.get("future"):
        base += " (с 2026)"
    return base

def money(x: float) -> str:
    return f"{x:,.2f}".replace(",", " ")

def parse_amount(token: str):
    try:
        return float(token.replace(",", ".").replace(" ", ""))
    except (ValueError, AttributeError):
        return None

def calc(ru: str, amount: float):
    c = COUNTRIES[ru]
    if c["rate"] is None:
        return None
    r = c["rate"]
    k = r / 100
    vat1 = amount * k
    gross = amount + vat1
    net2 = amount / (1 + k)
    vat2 = amount - net2
    return {
        "rate": r, "rate_str": fmt_rate(r),
        "amount": amount, "amount_str": money(amount),
        "vat_add": money(vat1), "gross": money(gross),
        "vat_extract": money(vat2), "net": money(net2),
    }